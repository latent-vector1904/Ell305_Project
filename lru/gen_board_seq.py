#!/usr/bin/env python3
"""Address list for the on-board LRU suite.

Eight analyzer tests, then four LRU victim rotations. The same list is written
into the sequencer ROM and into the simulation checker.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent


def add(tests, name, pairs):
    tests.append((name, pairs))


def build():
    tests = []
    add(tests, "temporal", [(0x00, 1)] + [(0x00, 0)] * 4)
    add(tests, "spatial", [
        (0x00, 1), (0x01, 0), (0x02, 0), (0x03, 0),
        (0x04, 1), (0x05, 0), (0x06, 0), (0x07, 0),
    ])
    add(tests, "conflict", [(0x00, 1), (0x10, 1), (0x00, 0), (0x10, 0)])
    add(tests, "capacity", (
        [(a, 1) for a in (0x00, 0x04, 0x08, 0x0C)]
        + [(a, 0) for a in (0x00, 0x04, 0x08, 0x0C)]
    ))
    add(tests, "replacement", [(0x00, 1), (0x00, 0), (0x10, 1), (0x00, 0)])
    add(tests, "independence", [(0x00, 1), (0x04, 1), (0x00, 0), (0x04, 0)])
    add(tests, "reverse", [(0x03, 1), (0x02, 0), (0x01, 0), (0x00, 0)])
    add(tests, "top", [(0xFC, 1), (0xFF, 0)])

    blocks = [0x00, 0x04, 0x08, 0x0C]
    for victim in range(4):
        pairs = [(b, 1) for b in blocks]
        pairs += [(b, 0) for k, b in enumerate(blocks) if k != victim]
        pairs.append((0x10, 1))
        pairs += [(b, 0) for k, b in enumerate(blocks) if k != victim]
        pairs.append((0x10, 0))
        pairs.append((blocks[victim], 1))
        add(tests, "victim_%02x" % blocks[victim], pairs)
    return tests


def main():
    tests = build()
    flat = []
    ends = []
    names_at = []
    phase_at = []
    for t_i, (name, pairs) in enumerate(tests):
        phase = t_i if t_i < 8 else (t_i - 8)
        for addr, miss in pairs:
            names_at.append(name)
            phase_at.append(phase)
            flat.append((addr, miss))
        ends.append(len(flat) - 1)

    assert len(flat) <= 128, len(flat)
    last = len(flat) - 1

    rom_lines = []
    end_terms = []
    phase_lines = []
    for i, ((addr, _miss), phase) in enumerate(zip(flat, phase_at)):
        rom_lines.append("                7'd%-3d: rom = 8'h%02X;" % (i, addr))
        phase_lines.append("            7'd%-3d: phase_of = 3'd%d;" % (i, phase))
    for e in ends:
        end_terms.append("i == 7'd%d" % e)

    seq = """// Address list generated by gen_board_seq.py. The suite repeats.
// The cache is cleared between tests. phase is the test number.
// Tests 0-7 are the analyzer suite. The four that follow are LRU victims
// (phase restarts at 0 and counts the victim index).
module lru_seq (
    input wire clk,
    input wire ce,
    input wire rst,
    input wire cache_idle,
    input wire done,
    output reg [7:0] address,
    output reg req,
    output reg clear_cache,
    output reg [2:0] phase
);
    localparam ISSUE = 2'd0, DROP = 2'd1, WAIT = 2'd2, GAP = 2'd3;

    reg [1:0] st;
    reg [6:0] n;
    reg [2:0] gap;

    localparam LAST = 7'd%d;

    function [7:0] rom;
        input [6:0] i;
        begin
            case (i)
%s
                default: rom = 8'h00;
            endcase
        end
    endfunction

    function is_end;
        input [6:0] i;
        begin
            is_end = %s;
        end
    endfunction

    function [2:0] phase_of;
        input [6:0] i;
        begin
            case (i)
%s
                default: phase_of = 3'd0;
            endcase
        end
    endfunction

    always @(posedge clk) begin
        if (rst) begin
            st <= ISSUE;
            n <= 7'd0;
            gap <= 3'd0;
            address <= 8'h00;
            req <= 1'b0;
            clear_cache <= 1'b0;
            phase <= 3'd0;
        end else if (ce) begin
            req <= 1'b0;
            case (st)
                ISSUE: begin
                    clear_cache <= 1'b0;
                    phase <= phase_of(n);
                    if (cache_idle && !done) begin
                        address <= rom(n);
                        req <= 1'b1;
                        st <= DROP;
                    end
                end
                DROP: st <= WAIT;
                WAIT: begin
                    if (done) begin
                        if (is_end(n)) begin
                            n <= (n == LAST) ? 7'd0 : n + 7'd1;
                            clear_cache <= 1'b1;
                            gap <= 3'd0;
                            st <= GAP;
                        end else begin
                            n <= n + 7'd1;
                            st <= ISSUE;
                        end
                    end
                end
                GAP: begin
                    clear_cache <= 1'b1;
                    phase <= phase_of(n);
                    if (gap == 3'd4) begin
                        clear_cache <= 1'b0;
                        st <= ISSUE;
                    end else begin
                        gap <= gap + 3'd1;
                    end
                end
                default: st <= ISSUE;
            endcase
        end
    end
endmodule
""" % (last, "\n".join(rom_lines), " || ".join(end_terms), "\n".join(phase_lines))

    seq_path = ROOT / "ffpga" / "src" / "lru_seq.v"
    seq_path.parent.mkdir(parents=True, exist_ok=True)
    seq_path.write_text(seq)

    exp_lines = []
    for i, (addr, miss) in enumerate(flat):
        exp_lines.append(
            "        7'd%-3d: board_expect = {1'b%d, 8'h%02X};" % (i, miss, addr)
        )
    width = max(len(n) for n in names_at)
    name_lines = []
    for i, name in enumerate(names_at):
        name_lines.append(
            '        7\'d%-3d: board_name = "%s";' % (i, name.ljust(width))
        )
    end_lines = []
    for e in ends:
        end_lines.append("        7'd%-3d: board_is_end = 1'b1;" % e)
    exp = """// Generated by gen_board_seq.py. Do not edit.
function [8:0] board_expect;
    input [6:0] i;
    begin
        case (i)
%s
            default: board_expect = {1'b0, 8'h00};
        endcase
    end
endfunction

function [%d:0] board_name;
    input [6:0] i;
    begin
        case (i)
%s
            default: board_name = "%s";
        endcase
    end
endfunction

function board_is_end;
    input [6:0] i;
    begin
        case (i)
%s
            default: board_is_end = 1'b0;
        endcase
    end
endfunction

localparam BOARD_N = %d;
""" % (
        "\n".join(exp_lines),
        width * 8 - 1,
        "\n".join(name_lines),
        " " * width,
        "\n".join(end_lines),
        len(flat),
    )
    (ROOT / "expect_rom.vh").write_text(exp)
    print("accesses %d  last %d  tests %d" % (len(flat), last, len(tests)))
    for name, pairs in tests:
        shape = "".join("M" if m else "H" for _a, m in pairs)
        print("  %-14s %s" % (name, shape))


if __name__ == "__main__":
    main()
